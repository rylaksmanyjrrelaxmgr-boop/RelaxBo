def analyze_sentiment(text: str) -> dict:
    """تحليل مشاعر النص بلهجة سعودية"""
    text_normalized = normalize_arabic(text)
    words = re.findall(
        r'\w+|[\U0001F600-\U0001F64F\U0001F300-\U0001F5FF'
        r'\U0001F680-\U0001F6FF\U0001F1E0-\U0001F1FF'
        r'\u2600-\u26FF\u2700-\u27BF]',
        text_normalized,
    )

    positive_count = 0
    negative_count = 0

    for word in words:
        if word in POSITIVE_WORDS:
            positive_count += 1
        elif word in NEGATIVE_WORDS:
            negative_count += 1

    total = positive_count + negative_count

    if total == 0:
        sentiment = "محايد 😐"
        emoji = "😐"
        response = "شكلك محايد، قول لنا أكثر يالطيب!"
    elif positive_count > negative_count:
        sentiment = "إيجابي 😊"
        emoji = "😊"
        response = "كلامك إيجابي، ياسلام عليك! 🌟"
    elif negative_count > positive_count:
        sentiment = "سلبي 😔"
        emoji = "😔"
        response = "شكلك متضايق، لا تشيل هم ترى الدنيا بخير 🌹"
    else:
        sentiment = "مختلط 🤔"
        emoji = "🤔"
        response = "مشاعرك مختلطة، عادي ياخوي!"

    positive_percent = (positive_count / total * 100) if total > 0 else 0
    negative_percent = (negative_count / total * 100) if total > 0 else 0

    return {
        'sentiment': sentiment,
        'emoji': emoji,
        'response': response,
        'positive_count': positive_count,
        'negative_count': negative_count,
        'positive_percent': positive_percent,
        'negative_percent': negative_percent,
        'total_words': len(words)
    }


